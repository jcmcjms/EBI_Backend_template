using Microsoft.AspNetCore.Hosting;
using Microsoft.AspNetCore.Mvc.Testing;
using Microsoft.Data.SqlClient;
using Template.Api.Tests.Testing;

namespace Template.Api.Tests.Integration;

/// <summary>
/// Runs the real application against a real SQL Server, per the testing rules (EF InMemory is not
/// proof of relational behavior). SQL Server is not assumed to exist on every machine: set
/// TEMPLATE_API_TEST_SQLSERVER to a server-level connection string (no Database segment needed) and
/// the fixture creates a uniquely named database, migrates it, seeds it, and drops it afterwards.
/// Without the variable, tests report an explicit skip with instructions instead of silently passing.
/// Example (docker compose from the repository root):
///   TEMPLATE_API_TEST_SQLSERVER="Server=localhost,1433;User Id=sa;Password=LocalDevPassword1!;TrustServerCertificate=True"
/// </summary>
public sealed class SqlServerIntegrationFixture : WebApplicationFactory<Program>, IAsyncLifetime
{
    public const string ServerConnectionStringEnvVar = "TEMPLATE_API_TEST_SQLSERVER";
    public const string SeedAdminEmail = "integration-admin@localhost.test";
    public const string SeedAdminPassword = "IntegrationAdminPassword123!";

    private readonly string? _serverConnectionString = Environment.GetEnvironmentVariable(ServerConnectionStringEnvVar);
    private readonly string _databaseName = $"tpl_it_{Guid.NewGuid():N}";

    public bool IsAvailable => !string.IsNullOrWhiteSpace(_serverConnectionString);

    public string DatabaseConnectionString =>
        new SqlConnectionStringBuilder(_serverConnectionString) { InitialCatalog = _databaseName }.ConnectionString;

    protected override void ConfigureWebHost(IWebHostBuilder builder)
    {
        builder.UseEnvironment("Testing");
        builder.UseSetting("ConnectionStrings:Database", DatabaseConnectionString);
        builder.UseSetting("Database:ApplyMigrations", "true");
        builder.UseSetting("Auth:Issuer", TestAuth.Issuer);
        builder.UseSetting("Auth:Audience", TestAuth.Audience);
        builder.UseSetting("Auth:SigningKey", TestAuth.SigningKey);
        builder.UseSetting("Seed:AdminEmail", SeedAdminEmail);
        builder.UseSetting("Seed:AdminPassword", SeedAdminPassword);
        // Integration flows issue many credential calls per minute; keep brute-force limits
        // from turning into order-dependent flakes. The limiter itself is framework-standard.
        builder.UseSetting("RateLimiting:AuthenticationPermitLimit", "100000");
    }

    /// <summary>Fails the test as an explicit, visible skip when SQL Server is not configured.</summary>
    public void SkipIfUnavailable()
    {
        if (!IsAvailable)
        {
            Assert.Skip(
                $"SQL Server is not available. Set {ServerConnectionStringEnvVar} to a server-level " +
                "connection string (see README \"Running the tests\"); the fixture creates and drops its own database.");
        }
    }

    public ValueTask InitializeAsync() => ValueTask.CompletedTask;

    public override async ValueTask DisposeAsync()
    {
        if (IsAvailable)
        {
            await DropDatabaseAsync();
        }

        await base.DisposeAsync();
    }

    private async Task DropDatabaseAsync()
    {
        try
        {
            var masterConnection = new SqlConnectionStringBuilder(_serverConnectionString) { InitialCatalog = "master" }.ConnectionString;
            await using var connection = new SqlConnection(masterConnection);
            await connection.OpenAsync();
            await using var command = connection.CreateCommand();
            // _databaseName is GUID-generated by this fixture, never external input.
            command.CommandText =
                $"IF DB_ID(N'{_databaseName}') IS NOT NULL " +
                $"BEGIN ALTER DATABASE [{_databaseName}] SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE [{_databaseName}]; END";
            await command.ExecuteNonQueryAsync();
        }
        catch (SqlException)
        {
            // Best-effort cleanup: a leftover database is named tpl_it_* and can be dropped manually.
        }
    }
}

[CollectionDefinition(Name)]
public sealed class SqlServerIntegrationCollectionDefinition : ICollectionFixture<SqlServerIntegrationFixture>
{
    public const string Name = "sqlserver-integration";
}
